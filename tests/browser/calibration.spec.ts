test('the UTF-8 body budget accepts 30000 bytes and blocks oversized content without truncating it', async ({ page }) => {
  await page.goto('/?view=calibration&entry=chart-implicit%3Aadj-crab-1')
  await page.getByRole('button', { name: '审阅通过', exact: true }).click()
  await page.getByRole('button', { name: '保存本条', exact: true }).click()
  const submit = page.getByRole('button', { name: '提交校准 Issue（1）', exact: true })
  await submit.click()
  const preview = page.getByRole('dialog', { name: '提交校准 Issue 预览' })
  const baseSize = Buffer.byteLength(await preview.getByLabel('完整 Issue 正文', { exact: true }).inputValue(), 'utf8')
  await preview.getByRole('button', { name: '返回编辑', exact: true }).click()
  const remaining = 30000 - baseSize
  const note = '中'.repeat(Math.floor(remaining / 3)) + 'x'.repeat(remaining % 3)
  await page.getByLabel('校准备注').fill(note)
  await page.getByRole('button', { name: '保存本条', exact: true }).click()
  await submit.click()
  expect(Buffer.byteLength(await preview.getByLabel('完整 Issue 正文', { exact: true }).inputValue(), 'utf8')).toBe(30000)
  await expect(preview.getByRole('link', { name: '打开 GitHub Issue 草稿', exact: true })).toBeVisible()
  await preview.getByRole('button', { name: '返回编辑', exact: true }).click()
  await page.getByLabel('校准备注').fill(note + '中')
  await page.getByRole('button', { name: '保存本条', exact: true }).click()
  await submit.click()
  await expect(preview.getByRole('alert')).toContainText('30,003 UTF-8 字节')
  await expect(preview.getByRole('alert')).toContainText('30,000')
  await expect(preview.getByRole('link', { name: '打开 GitHub Issue 草稿', exact: true })).toHaveCount(0)
  const oversized = JSON.parse(await preview.getByLabel('完整校准 JSON', { exact: true }).inputValue())
  expect(oversized.records[0].note).toBe(note + '中')
  await preview.getByRole('checkbox').uncheck()
  await expect(preview).not.toContainText('30,003 UTF-8 字节')
  await preview.getByRole('button', { name: '返回编辑', exact: true }).click()
  await expect(page.getByLabel('校准备注')).toHaveValue(note + '中')
  await page.getByLabel('校准备注').fill('缩短后的备注')
  await page.getByRole('button', { name: '保存本条', exact: true }).click()
  await submit.click()
  await expect(preview.getByRole('link', { name: '打开 GitHub Issue 草稿', exact: true })).toBeVisible()
})

