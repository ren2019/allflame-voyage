test('a prototype export imports as review records and never overrides a later review', async ({ page }) => {
  await page.goto('/?view=calibration&entry=border%3Ab-sulphdrop')
  const file = { prototype: true, variant: 'A', records: [{ 类别: '边界词缀', 标识: 'b-sulphdrop', 英文: "Rare Monsters in adjacent Areas drop Dead Man's Sulphur", 当前中文: '相邻区域的稀有怪物掉落死者硫磺', 审阅: { status: 'change', suggestion: '原型建议待核对', note: '原型校准备注' } }] }
  const backup = { name: 'prototype.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(file)) }
  await page.getByLabel('导入校准记录').setInputFiles(backup)
  await expect(page.getByRole('status')).toContainText('已导入 1 条')
  await expect(page.getByLabel('建议中文')).toHaveValue('原型建议待核对')
  await expect(page.locator('.cal-inspector .cal-badge').first()).toHaveText('来源冲突')
  await page.getByLabel('建议中文').fill('正式校准记录')
  await page.getByRole('button', { name: '保存本条', exact: true }).click()
  await page.getByLabel('导入校准记录').setInputFiles(backup)
  await expect(page.getByRole('status')).toContainText('保留 1 条较新记录')
  await expect(page.getByLabel('建议中文')).toHaveValue('正式校准记录')
})
