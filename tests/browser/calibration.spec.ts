test('a single correction survives refresh and exports without changing source wording or evidence', async ({ page }) => {
  await page.goto('/?view=calibration&entry=chart-implicit%3Aadj-crab-1')
  await page.getByLabel('建议中文').fill('螃蟹词缀的校准建议')
  await page.getByLabel('校准备注').fill('需要核对高级复制原文，不自动应用。')
  await page.getByRole('button', { name: '需要修改', exact: true }).click()
  await page.getByRole('button', { name: '保存本条', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('已保存')
  await page.reload()
  await expect(page.getByLabel('建议中文')).toHaveValue('螃蟹词缀的校准建议')
  await expect(page.getByLabel('校准备注')).toHaveValue('需要核对高级复制原文，不自动应用。')
  await expect(page.locator('.cal-inspector .cal-badge').first()).toHaveText('客户端已校准')
  await expect(page.locator('.cal-comparison')).toContainText('相邻区域包含 (8—10) 个额外的螃蟹群')
  await page.getByLabel('搜索词库').fill('校准建议')
  await expect(page.getByRole('row')).toHaveCount(2)
  const downloaded = page.waitForEvent('download')
  await page.getByRole('button', { name: /导出校准记录/ }).click()
  const stream = await (await downloaded).createReadStream()
  const buffers = []
  for await (const chunk of stream) buffers.push(chunk)
  const recordFile = JSON.parse(Buffer.concat(buffers).toString('utf8'))
  expect(recordFile.format).toBe('allflame-calibration')
  expect(recordFile.version).toBe(1)
  expect(recordFile.records).toHaveLength(1)
  expect(recordFile.records[0].key).toBe('chart-implicit:adj-crab-1')
  expect(recordFile.records[0].suggestion).toBe('螃蟹词缀的校准建议')
  expect(recordFile.records[0].status).toBe('change')
  expect(recordFile.records[0].base.chinese).toBe('相邻区域包含 (8—10) 个额外的螃蟹群')
})

test('imports backups atomically and preserves newer records and unrelated drafts', async ({ page }) => {
  await page.goto('/?view=calibration&entry=chart-implicit%3Aadj-crab-1')
  await page.getByLabel('建议中文').fill('已保存的新建议')
  await page.getByRole('button', { name: '保存本条', exact: true }).click()
  const downloaded = page.waitForEvent('download')
  await page.getByRole('button', { name: /导出校准记录/ }).click()
  const stream = await (await downloaded).createReadStream()
  const chunks = []; for await (const chunk of stream) chunks.push(chunk)
  const file = JSON.parse(Buffer.concat(chunks).toString('utf8'))
  file.records[0].updatedAt = '2020-01-01T00:00:00.000Z'
  file.records[0].suggestion = '旧建议'
  await page.getByLabel('校准备注').fill('尚未保存的备注')
  await page.getByLabel('导入校准记录').setInputFiles({ name: 'backup.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(file)) })
  await expect(page.getByRole('status')).toContainText('保留 1 条较新记录')
  await expect(page.getByLabel('建议中文')).toHaveValue('已保存的新建议')
  await expect(page.getByLabel('校准备注')).toHaveValue('尚未保存的备注')
  file.records.push({ ...file.records[0], key: 'unknown:bad' })
  await page.getByLabel('导入校准记录').setInputFiles({ name: 'invalid.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(file)) })
  await expect(page.getByRole('status')).toContainText('导入失败')
  await expect(page.getByLabel('建议中文')).toHaveValue('已保存的新建议')
  await page.getByRole('button', { name: '撤销未保存修改' }).click()
})

